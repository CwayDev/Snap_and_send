import os
from dotenv import load_dotenv
from google import genai

load_dotenv()

def run_language_test():
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise ValueError("GEMINI_API_KEY not found in environment!")

    client = genai.Client(api_key=api_key)
    model_name = "gemma-4-26b-a4b-it"

    languages = [lang.strip() for lang in os.getenv("TARGET_LANGUAGES", "Hausa,French").split(",") if lang.strip()]
    if "English" not in languages:
        languages.insert(0, "English")

    sample_product_info = (
        "Item: Paracetamol 500mg Tablets.\n"
        "Category: Medicine Box / Product.\n"
        "Active Ingredients: Acetaminophen (Paracetamol) 500mg.\n"
        "Indications: For relief of mild to moderate pain, headaches, and reduction of fever.\n"
        "Dosage: Adults take 1-2 tablets every 4-6 hours as needed. Do not exceed 8 tablets in 24 hours.\n"
        "Safety Warning: Keep out of reach of children. Consult a doctor if symptoms persist."
    )

    md_output = [
        "# Multilingual Quality Verification Benchmark (Gemma 4)",
        "",
        "This document records the exact translations and explanations generated by **Gemma 4** (`gemma-4-26b-a4b-it`) across supported target languages. Native and fluent speakers can evaluate terminology, medical/label accuracy, and tone.",
        "",
        "## Source Grounded Context",
        "```text",
        sample_product_info,
        "```",
        "",
        "---",
        ""
    ]

    for lang in languages:
        print(f"Generating explanation in {lang} using Gemma 4...")
        prompt = (
            f"You are the multilingual engine for 'Snap & Understand'. "
            f"Explain the following grounded product details clearly, accurately, and naturally in {lang}. "
            f"Maintain proper terminology for medical and product instructions. Avoid unnecessary filler.\n\n"
            f"DETAILS:\n{sample_product_info}"
        )
        try:
            resp = client.models.generate_content(
                model=model_name,
                contents=prompt
            )
            text = resp.text.strip()
            md_output.append(f"### Language: {lang}")
            md_output.append(f"- **Status:** Verified with `{model_name}`")
            md_output.append(f"- **Generated Output:**")
            md_output.append("")
            md_output.append(text)
            md_output.append("")
            md_output.append("---")
            md_output.append("")
        except Exception as e:
            print(f"Error testing {lang}: {e}")
            md_output.append(f"### Language: {lang}")
            md_output.append(f"- **Error:** {str(e)}")
            md_output.append("")

    with open("docs/language-test.md", "w", encoding="utf-8") as f:
        f.write("\n".join(md_output))

    print("Multilingual verification log updated in docs/language-test.md")

if __name__ == "__main__":
    run_language_test()
